"""1등 판매점 정보가 존재하는 회차 구간.

동행복권은 **261회차 이하의 1등 판매점을 공개하지 않는다** (2026-08-06 실측).
262회차(2007-12-08)부터 데이터가 있고, 그 이후로는 1등 당첨자가 있는 한
빠짐없이 존재한다. 자동/수동 구분(winType)이 시작되는 회차와 같다 —
동행복권이 그 시점부터 상세 정보를 공개하기 시작한 것으로 보인다.

이 경계를 모르면 두 가지 사고가 난다.
  1. 검증이 261회차 이하 250개를 '판매점 0건'으로 오탐해 배치가 영구 실패
  2. 항상 빈 응답이 올 회차에 요청을 날려 IP 차단 예산을 낭비
"""

STORE_DATA_FIRST_ROUND = 262


def has_store_data(round_no):
    """해당 회차에 판매점 정보가 존재할 수 있는가."""
    return round_no >= STORE_DATA_FIRST_ROUND
